"""Alembic baseline and stamp/upgrade behavior on disposable SQLite files."""
import sqlite3

import pytest
from alembic.util.exc import AutogenerateDiffsDetected

from bdt import migrate
from bdt.storage import Database


def _url(tmp_path, name="migration.db"):
    return f"sqlite:///{(tmp_path / name).as_posix()}"


def _tables(path):
    with sqlite3.connect(path) as connection:
        return {row[0] for row in connection.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")}


def test_empty_database_upgrades_to_the_full_baseline(tmp_path):
    url = _url(tmp_path)
    migrate.upgrade(url)
    tables = _tables(tmp_path / "migration.db")
    assert {"alembic_version", "schema_version", "users", "places", "community_groups",
            "ocr_jobs", "pncp_contract_documents", "document_originals",
            "transferegov_parcerias", "transferegov_parceria_empenhos"} <= tables
    with sqlite3.connect(tmp_path / "migration.db") as connection:
        assert connection.execute("SELECT id, version FROM schema_version").fetchone() == (1, 1)
        assert connection.execute("SELECT version_num FROM alembic_version").fetchone() == (
            "0003_parceria_empenhos",)
    migrate.check(url)
    Database(url).initialize()


def test_explicit_database_wins_over_inherited_environment(tmp_path, monkeypatch):
    environment_url = _url(tmp_path, "environment.db")
    requested_url = _url(tmp_path, "requested.db")
    monkeypatch.setenv("BDT_DATABASE_URL", environment_url)

    migrate.upgrade(requested_url)

    assert (tmp_path / "requested.db").is_file()
    assert "users" in _tables(tmp_path / "requested.db")
    assert not (tmp_path / "environment.db").exists()


def test_existing_bootstrap_is_stamped_and_upgrade_is_idempotent(tmp_path):
    url = _url(tmp_path)
    database = Database(url)
    database.initialize()
    database.engine.dispose()

    migrate.stamp(url)
    migrate.upgrade(url)
    migrate.check(url)
    database = Database(url)
    database.initialize()
    database.engine.dispose()


def test_check_detects_schema_drift(tmp_path):
    url = _url(tmp_path)
    migrate.upgrade(url)
    with sqlite3.connect(tmp_path / "migration.db") as connection:
        connection.execute("DROP TABLE document_originals")
    with pytest.raises(AutogenerateDiffsDetected):
        migrate.check(url)
